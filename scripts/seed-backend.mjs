async function api(path, { method = 'GET', body, token } = {}) {
  const res = await fetch(`${BASE}/api/v1${path}`, {
    method,
    headers: {
      'Content-Type': 'application/json',
      ...(token ? { Authorization: `Bearer ${token}` } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  })
  const json = await res.json().catch(() => null)
  if (!res.ok || !json?.isSuccess) {
    throw new Error(`${method} ${path} → ${res.status}: ${json?.errors?.join('; ') || json?.message || res.statusText}`)
  }
  return json.data
}

async function main() {
  console.log(`→ Вход как ${EMAIL} на ${BASE} ...`)
  const tokens = await api('/Authentication/login', { method: 'POST', body: { email: EMAIL, password: PASSWORD } })
  const token = tokens.accessToken
  console.log('✓ Авторизация прошла успешно.')

  for (const tpl of TEMPLATES) {
    console.log(`\n→ Шаблон «${tpl.name}»`)
    const templateId = await api('/Templates', {
      method: 'POST',
      token,
      body: { name: tpl.name, description: tpl.descRu, language: 'Both', maintainedByRef: 'seed-script' },
    })
    console.log(`  ✓ создан (${templateId})`)

    let order = 0
    for (const clause of tpl.clauses) {
      const clauseBlockId = await api('/ClauseBlocks', {
        method: 'POST',
        token,
        body: { title: clause.title, contentRu: clause.ru, contentTj: clause.tj, category: tpl.name },
      })
      await api(`/Templates/${templateId}/clause-blocks`, {
        method: 'POST',
        token,
        body: { clauseBlockId, isDefault: true, order: order++ },
      })
      console.log(`  ✓ пункт «${clause.title}» прикреплён`)
    }
  }

  console.log('\nГотово. Библиотека шаблонов загружена в реальный бэкенд.')
}

main().catch((err) => {
  console.error('\n✗', err.message)
  process.exit(1)
})
